"use client";

import { useState } from "react";

interface AiBuyerReviewProps {
  listingId: string;
  existingReview?: string | null;
}

/**
 * Shows a cached AI buyer review or lets any visitor generate one on demand.
 */
export function AiBuyerReview({ listingId, existingReview }: AiBuyerReviewProps) {
  const [review, setReview] = useState<string | null>(existingReview ?? null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function handleGenerate() {
    setLoading(true);
    setError(null);

    try {
      const response = await fetch("/api/ai-review", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ listingId }),
      });

      const result = (await response.json()) as {
        review?: string;
        error?: string;
      };

      if (result.review) {
        setReview(result.review);
      } else {
        setError(result.error ?? "Could not generate review. Try again.");
      }
    } catch {
      setError("Could not connect to AI service.");
    } finally {
      setLoading(false);
    }
  }

  // Format bullet points (lines starting with • or - or *)
  function formatReview(text: string) {
    const lines = text.split("\n").filter((line) => line.trim());
    return lines.map((line, index) => {
      const isBullet = /^[•\-\*]/.test(line.trim());
      const cleanLine = line.replace(/^[•\-\*]\s*/, "");
      return isBullet ? (
        <li key={index} className="flex items-start gap-2">
          <span className="mt-0.5 shrink-0 text-[#0f6b4e]">✓</span>
          <span>{cleanLine}</span>
        </li>
      ) : (
        <p key={index} className="text-sm leading-relaxed text-[#4b5e55]">
          {line}
        </p>
      );
    });
  }

  return (
    <div className="rounded-2xl border border-[#e4dccb] bg-white p-6 shadow-sm">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <span className="inline-flex items-center gap-1.5 rounded-full bg-[#e6f4ee] px-3 py-1 text-xs font-semibold text-[#0f6b4e]">
            ✦ AI Buyer Review
          </span>
          <p className="mt-1.5 text-xs text-[#4b5e55]">
            AI-generated highlights and tips for renters — based on listing details.
          </p>
        </div>
        {!review && (
          <button
            type="button"
            onClick={handleGenerate}
            disabled={loading}
            className="shrink-0 rounded-xl bg-[#0f6b4e] px-4 py-2 text-xs font-semibold text-white transition-colors hover:bg-[#094c37] disabled:opacity-60"
          >
            {loading ? "Analyzing PG…" : "Get AI Review"}
          </button>
        )}
      </div>

      {error ? (
        <p className="mt-4 rounded-xl border border-red-200 bg-red-50 p-3 text-xs text-red-800">
          {error}
        </p>
      ) : null}

      {review ? (
        <div className="mt-5 space-y-3">
          <ul className="space-y-2 text-sm font-medium text-[#14261f]">
            {formatReview(review)}
          </ul>
          <p className="border-t border-[#f3ede0] pt-3 text-[11px] text-[#4b5e55]">
            Generated by Gemini AI · Always verify details with the owner before booking.
          </p>
        </div>
      ) : !error && !loading ? (
        <div className="mt-4 rounded-xl border border-dashed border-[#e4dccb] bg-[#fbf8f1] p-4 text-center text-xs text-[#4b5e55]">
          Click <strong>Get AI Review</strong> to see highlights and tips for this PG.
        </div>
      ) : null}

      {loading ? (
        <div className="mt-4 space-y-2">
          {[1, 2, 3].map((i) => (
            <div
              key={i}
              className="h-4 animate-pulse rounded-lg bg-[#f3ede0]"
              style={{ width: `${80 - i * 10}%` }}
            />
          ))}
        </div>
      ) : null}
    </div>
  );
}
